"""Generate matching backend/mobile catalogues and ship the credited photo files.

Photo metadata is refreshed with build_species_references.py, reviewed visually,
then written to backend/data/species_reference.json. This command can also reuse
that checked-in catalogue without any network or research cache.
"""
import json
from pathlib import Path
import shutil
from curated_species_facts import facts, add_comparisons

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'mobile/tmp/species_sources'
TARGET = ROOT / 'backend/data/species_reference.json'

def main():
    previous = json.loads(TARGET.read_text(encoding='utf-8')) if TARGET.exists() else {}
    catalog = facts()
    add_comparisons(catalog)
    def photos(name):
        alternative = CACHE / (name.replace(' ', '_') + '_photos.json')
        if alternative.exists():
            return json.loads(alternative.read_text(encoding='utf-8'))
        meta = CACHE / (name.replace(' ', '_') + '_commons.json')
        if meta.exists():
            return json.loads(meta.read_text(encoding='utf-8'))
        if name in previous:
            return previous[name].get('reference_photos', [])
        for value in previous.values():
            for comparison in value.get('similar_species_records', []):
                if comparison['scientific_name'] == name:
                    return comparison.get('photos', [])
        return []
    for name, value in catalog.items():
        photo_taxon = 'Eucalyptus deglupta' if name == 'Eucalyptus' else name
        value['reference_photos'] = photos(photo_taxon)
        if name == 'Tabebuia rosea' and not value['reference_photos']:
            for file, source, caption in [
                ('pink_poui_flowers.jpg','Starr_061206-1952_Tabebuia_rosea.jpg','Pink poui flowers'),
                ('pink_poui_leaves_flowers.jpg','Starr_070221-4759_Tabebuia_rosea.jpg','Pink poui leaves and flowers')]:
                value['reference_photos'].append(dict(asset='assets/reference_photos/'+file,
                    caption=caption, author='Forest & Kim Starr', license='CC BY 3.0',
                    license_url='https://creativecommons.org/licenses/by/3.0/',
                    source_url='https://commons.wikimedia.org/wiki/File:'+source,
                    scientific_name=name))
        if name == 'Eucalyptus':
            for photo in value['reference_photos']:
                photo['caption'] = 'Genus example: Eucalyptus deglupta - not the confirmed species'
        for comparison in value.get('similar_species_records', []):
            comparison['photos'] = photos(comparison['scientific_name'])
            if comparison['scientific_name'] == 'Tabebuia rosea':
                comparison['photos'] = catalog['Tabebuia rosea']['reference_photos'] if 'reference_photos' in catalog['Tabebuia rosea'] else previous.get('Tabebuia rosea',{}).get('reference_photos',[])
    credits = []
    for value in catalog.values():
        for comparison in value.get('similar_species_records', []):
            if comparison['scientific_name'] in catalog:
                comparison['photos'] = catalog[comparison['scientific_name']]['reference_photos']
    for value in catalog.values():
        groups = [value.get('reference_photos', [])] + [c.get('photos', []) for c in value.get('similar_species_records', [])]
        for group in groups:
            for photo in group:
                filename = Path(photo['asset']).name
                photo['url'] = '/species-reference/' + filename
                photo.pop('description', None)
                source = ROOT / 'mobile' / photo['asset']
                dest = ROOT / 'frontend/public/species-reference' / filename
                if not source.exists():
                    raise RuntimeError(f'Missing bundled photo: {source}')
                dest.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, dest)
                credits.append(f"{filename}\n{photo['scientific_name']}\n{photo['author']} | {photo['license']}\n{photo['source_url']}\n{photo['license_url']}\nDisplayed to fit; no botanical alterations.\n")
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(json.dumps(catalog, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    dart = '// Generated by tools/export_species_catalog.py; edit the source catalogue.\n'
    dart += 'const speciesReferenceCatalog = <String, dynamic>' + json.dumps(catalog, ensure_ascii=True, indent=2).replace('$', '\\$') + ';\n'
    (ROOT/'mobile/lib/services/species_reference_catalog.dart').write_text(dart,encoding='utf-8')
    text = 'Species reference photographs. Individual licences apply.\n\n' + '\n'.join(dict.fromkeys(credits))
    (ROOT/'mobile/assets/reference_photos/CREDITS.txt').write_text(text,encoding='utf-8')
    (ROOT/'frontend/public/species-reference/CREDITS.txt').write_text(text,encoding='utf-8')
    print(json.dumps({k:len(v['reference_photos']) for k,v in catalog.items()}))

if __name__ == '__main__':
    main()
